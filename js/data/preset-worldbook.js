export async function initPresetWorldbook(db, userId) {
  if (!userId) return; // 没用户直接跳过

  // 检查这个用户是不是已经导入过了
  const initKey = `worldbook_initialized_${userId}`;
  const wbInit = await db.get("settings", initKey);
  if (wbInit && wbInit.value) return; // 已经导过了，直接跳过

  // 开始导入
  for (const entry of PRESET_WORLDBOOK) {
    // 重点：把 ownerId 绑定到当前用户身上！
    await db.put("world_book", { ...entry, ownerId: userId });
  }
  
  // 打个标记，以后这个用户就不会再重复导入了
  await db.put("settings", { key: initKey, value: true });
}