/**
 * 抽签（按分类每日各一次）
 * @param {string} ownerId 
 * @param {string} category 感情 / 事业 / 平安
 */
export async function drawSign(ownerId, category = "感情") {
  const today = new Date().toISOString().slice(0, 10);

  // 检查今天该分类是否已抽
  const all = await db.all("divinations");
  const todaySign = all.find(d =>
    d.ownerId === ownerId &&
    d.type === "sign" &&
    d.dateKey === today &&
    d.category === category
  );

  if (todaySign) {
    return { already: true, record: todaySign };
  }

  // 按权重抽
  const grades = Object.keys(SIGN_WEIGHTS);
  const total = grades.reduce((a, g) => a + SIGN_WEIGHTS[g], 0);
  let r = Math.random() * total;
  let level = "中吉";
  for (const g of grades) {
    r -= SIGN_WEIGHTS[g];
    if (r <= 0) {
      level = g;
      break;
    }
  }

  // 获取对应分类对应等级的签文池
  const pool = SIGN_TEXTS[category]?.[level];
  if (!pool || !pool.length) return null;
  
  const sign = pool[Math.floor(Math.random() * pool.length)];

  const record = {
    id: uid("sign"),
    ownerId,
    type: "sign",
    category: category, // 👈 增加分类记录
    dateKey: today,
    level,
    poem: sign.poem,
    meaning: sign.meaning,
    createdAt: Date.now(),
  };

  await db.put("divinations", record);
  return { already: false, record };
}

/**
 * 获取抽签历史
 */
export async function getSignHistory(ownerId) {
  const all = await db.all("divinations");
  return all
    .filter(d => d.ownerId === ownerId && d.type === "sign")
    .sort((a, b) => b.createdAt - a.createdAt);
}

