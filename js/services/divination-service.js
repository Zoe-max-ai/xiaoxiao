/**
 * 问易 · 起卦（金钱卦）
 */
export async function drawBagua(ownerId, question = "") {
  // 三枚铜钱摇六次
  const lines = [];
  const movingLines = [];
  for (let i = 0; i < 6; i++) {
    let sum = 0;
    for (let k = 0; k < 3; k++) sum += Math.random() < 0.5 ? 2 : 3;
    let val;
    let isMoving = false;
    if (sum === 6) { val = 0; isMoving = true; }       // 老阴
    else if (sum === 7) { val = 1; }                    // 少阳
    else if (sum === 8) { val = 0; }                    // 少阴
    else { val = 1; isMoving = true; }                  // 老阳
    lines.push(val);
    if (isMoving) movingLines.push(i + 1);
  }

  const upper = lines.slice(3, 6).map(v => v === 1 ? '1' : '0').join('');
  const lower = lines.slice(0, 3).map(v => v === 1 ? '1' : '0').join('');
  const upperName = TRIGRAM_NAMES[upper];
  const lowerName = TRIGRAM_NAMES[lower];
  const key = upperName + lowerName;
  const raw = GUA_DATA[key];
  if (!raw) {
    console.error("[bagua] 未知卦象:", key);
    return null;
  }
  const parts = raw.split('|');
  const name = parts[0];
  const ci = parts[1] || '';
  const xiang = parts[2] || '';
  const modern = GUA_MODERN[name] || '宜静观其变，审时度势。';

  const record = {
    id: uid("bagua"),
    ownerId,
    type: "bagua",
    method: "coin",
    question,
    lines,
    movingLines,
    benGua: name,
    upper: upperName,
    lower: lowerName,
    guaCi: ci,
    xiangCi: xiang,
    interpretation: modern,
    createdAt: Date.now(),
  };

  await db.put("divinations", record);
  return record;
}

/**
 * 获取问易历史
 */
export async function getBaguaHistory(ownerId) {
  const all = await db.all("divinations");
  return all
    .filter(d => d.ownerId === ownerId && d.type === "bagua")
    .sort((a, b) => b.createdAt - a.createdAt);
}